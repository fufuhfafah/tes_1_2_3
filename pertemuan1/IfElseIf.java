public class IfElseIf {
    public static void main(String[] args) {
        int nilai = 80;

        if (nilai >= 90) {
            System.out.println("Sangat Baik");
        } else if (nilai >= 75) {
            System.out.println("Baik");
        } else {
            System.out.println("Kurang");
        }
    }
}
